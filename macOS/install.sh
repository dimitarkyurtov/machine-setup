#!/bin/zsh

# Ghostty terminal emulator - https://ghostty.org/docs
brew install --cask ghostty

# Fuzzy finder - https://github.com/junegunn/fzf
brew install fzf

# Starship prompt - https://starship.rs
brew install starship

# Syntax highlighing - https://github.com/zsh-users/zsh-syntax-highlighting
brew install zsh-syntax-highlighting

# ls alternative - https://github.com/eza-community/eza
brew install eza

# cd alternative - https://github.com/ajeetdsouza/zoxide
brew install zoxide

# Faster grep - https://github.com/burntsushi/ripgrep 
brew install ripgrep

# Faster find - https://github.com/sharkdp/fd#installation
brew install fd

# Cat with colors - https://github.com/sharkdp/bat 
brew install bat

# Dotfiles managing
brew install stow

# System information - https://github.com/fastfetch-cli/fastfetch
brew install fastfetch

# Windowing manager - https://github.com/nikitabobko/aerospace
brew install --cask nikitabobko/tap/aerospace

# Janky borders - https://github.com/FelixKratz/JankyBorders#bootstrap-with-aerospace
brew install --cask felixkratz/tap/jankyborders